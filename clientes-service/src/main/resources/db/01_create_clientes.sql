CREATE TABLE CLIENTES (
    CLIENTE_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUENTA_ID            NUMBER NOT NULL,
    NOMBRE               VARCHAR2(120) NOT NULL,
    EDAD                 NUMBER(3) NOT NULL,
    PERFIL               VARCHAR2(30) DEFAULT 'ESTANDAR' NOT NULL,
    ESTADO               VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT UK_CLIENTES_CUENTA
        UNIQUE (CUENTA_ID),

    CONSTRAINT CK_CLIENTES_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')),

    CONSTRAINT CK_CLIENTES_PERFIL
        CHECK (PERFIL IN ('ESTANDAR', 'PREFERENTE'))
);

MERGE INTO CLIENTES destino
USING (
    SELECT
        CUENTA_ID,
        NOMBRE,
        EDAD,
        CASE
            WHEN ESTADO = 'VALIDA' THEN 'ACTIVO'
            ELSE 'INACTIVO'
        END AS ESTADO_CLIENTE
    FROM INTERESES_PROCESADOS
    WHERE NOMBRE IS NOT NULL
      AND EDAD IS NOT NULL
) origen
ON (destino.CUENTA_ID = origen.CUENTA_ID)

WHEN NOT MATCHED THEN
    INSERT (
        CUENTA_ID,
        NOMBRE,
        EDAD,
        PERFIL,
        ESTADO,
        FECHA_CREACION,
        FECHA_ACTUALIZACION
    )
    VALUES (
        origen.CUENTA_ID,
        origen.NOMBRE,
        origen.EDAD,
        'ESTANDAR',
        origen.ESTADO_CLIENTE,
        SYSTIMESTAMP,
        SYSTIMESTAMP
    );